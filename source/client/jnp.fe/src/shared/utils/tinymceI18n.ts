/**
 * Đăng ký ngôn ngữ cho TinyMCE
 */
export const registerVietnamese = (editor: any) => {
    if (editor && editor.editorManager) {
        editor.editorManager.addI18n('vi', viVN);
    } else if (window.tinymce) {
        window.tinymce.addI18n('vi', viVN);
    }
};
